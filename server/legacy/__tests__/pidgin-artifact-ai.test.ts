import { env as bindings } from "cloudflare:workers";
import { applyD1Migrations, type D1Migration } from "cloudflare:test";
import { afterEach, beforeAll, describe, expect, it } from "vitest";
import worker from "../index";
import { sha256Hex } from "../auth-utils";
import { artifactAI, setArtifactAI } from "../artifact-ai";
import type { Env } from "../types";

// The optional artifactAI() hook: a deployment may compose long documents
// into pages. With none registered the route publishes a plain artifact.

const env = {
  ...bindings,
  API_KEY: "artifact-ai-test-key",
  OWNER_EMAIL: "owner@example.com",
  WORKER_URL: "https://pidgindocs.example.workers.dev",
  ENVIRONMENT: "production",
} as unknown as Env & { TEST_MIGRATIONS: D1Migration[] };
const ctx = { waitUntil() {}, passThroughOnException() {} } as unknown as ExecutionContext;

beforeAll(async () => { await applyD1Migrations(env.DB, env.TEST_MIGRATIONS); });
afterEach(() => setArtifactAI(null));

type Json = any;

async function makeUser(label: string) {
  const id = `${label}-${crypto.randomUUID().slice(0, 8)}`;
  const token = `pidgin_sk_${id}`;
  await env.DB.prepare("INSERT INTO users (id, email, status) VALUES (?, ?, 'active')").bind(id, `${id}@example.com`).run();
  await env.DB.prepare("INSERT INTO api_keys (key_hash, key_prefix, user_id) VALUES (?, ?, ?)")
    .bind(await sha256Hex(token), "pidgin_sk", id).run();
  const publish = async (body: unknown) => {
    const res = await worker.fetch(new Request("https://pidgindocs.example.workers.dev/api/artifacts", {
      method: "POST", headers: { Authorization: `Bearer ${token}`, "Content-Type": "application/json" }, body: JSON.stringify(body),
    }), env, ctx);
    return { status: res.status, body: (await res.json()) as Json };
  };
  return { id, publish };
}

const base = { title: "Long doc", favicon: "📄", markdown: "# Heading\n\nSome long text." };

describe("artifactAI hook", () => {
  it("defaults to none", () => {
    expect(artifactAI()).toBeNull();
  });

  it("without a hook, ai:true publishes a plain artifact and says ai: none", async () => {
    const u = await makeUser("a");
    const r = await u.publish({ ...base, ai: true });
    expect(r.status).toBe(201);
    expect(r.body.data.ai).toBe("none");
    expect(r.body.data.version).toBe(1);
    const found = await env.DB.prepare("SELECT r2_key FROM artifact_versions WHERE artifact_id = ?").bind(r.body.data.id).first<{ r2_key: string }>();
    const html = await (await env.DOCS.get(found!.r2_key))!.text();
    expect(html).toContain("Heading"); // the markdown, typeset as is
  });

  it("without ai, nothing about ai appears", async () => {
    const u = await makeUser("b");
    const r = await u.publish(base);
    expect(r.status).toBe(201);
    expect("ai" in r.body.data).toBe(false);
  });

  it("with a hook, ai:true publishes what the hook composed and says generated", async () => {
    const u = await makeUser("c");
    const seen: Json[] = [];
    setArtifactAI({
      async generate(_env, userId, input) {
        seen.push({ userId, ...input });
        return { html: "<main>generated by the hook</main>" };
      },
    });
    const r = await u.publish({ ...base, ai: true });
    expect(r.status).toBe(201);
    expect(r.body.data.ai).toBe("generated");
    expect(seen).toEqual([{ userId: u.id, markdown: base.markdown, title: base.title }]);
    const found = await env.DB.prepare("SELECT r2_key FROM artifact_versions WHERE artifact_id = ?").bind(r.body.data.id).first<{ r2_key: string }>();
    expect(await (await env.DOCS.get(found!.r2_key))!.text()).toContain("generated by the hook");
  });

  it("the hook is not called unless the caller asked", async () => {
    const u = await makeUser("d");
    let calls = 0;
    setArtifactAI({ async generate() { calls++; return { html: "<p>x</p>" }; } });
    const r = await u.publish(base);
    expect(r.status).toBe(201);
    expect(calls).toBe(0);
    expect("ai" in r.body.data).toBe(false);
  });

  it("a hook that returns nothing or throws falls back to a plain artifact with ai: failed", async () => {
    const u = await makeUser("e");
    setArtifactAI({ async generate() { return null; } });
    expect((await u.publish({ ...base, ai: true })).body.data.ai).toBe("failed");
    setArtifactAI({ async generate() { throw new Error("model down"); } });
    const r = await u.publish({ ...base, ai: true });
    expect(r.status).toBe(201);
    expect(r.body.data.ai).toBe("failed");
  });

  it("ai:true with html input is ignored (nothing to compose)", async () => {
    const u = await makeUser("f");
    let calls = 0;
    setArtifactAI({ async generate() { calls++; return { html: "<p>x</p>" }; } });
    const r = await u.publish({ title: "Page", favicon: "📄", html: "<p>mine</p>", ai: true });
    expect(r.status).toBe(201);
    expect(calls).toBe(0);
  });

  it("a non-boolean ai is 400", async () => {
    const u = await makeUser("g");
    expect((await u.publish({ ...base, ai: "yes" })).status).toBe(400);
  });
});
